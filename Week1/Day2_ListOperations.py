numbers = [30, 10, 50, 20, 40]
print("Original List:")
print(numbers)


# Append
numbers.append(60)
print("\nAfter append(60):")
print(numbers)


# Insert
numbers.insert(2, 25)
print("\nAfter insert(2, 25):")
print(numbers)

# Remove
numbers.remove(10)
print("\nAfter remove(10):")
print(numbers)

# Sort
numbers.sort()
print("\nAfter sort():")
print(numbers)

# Reverse
numbers.reverse()
print("\nAfter reverse():")
print(numbers)
